package com.example.policy

/**
 * قواعد سلوك النموذج وتعليمات التوجيه المضمّنة في استدعاءات Gemini داخل التطبيق:
 * 1) مساعد هاتف ذكي يتحدث العربية ويفهم الأوامر.
 * 2) يتحقق من الشاشة الحقيقية قبل كل فعل، ولا يخترع أسماء تطبيقات أو أزرار.
 * 3) يسأل المستخدم قبل أي فعل حساس (حذف، إرسال، تغيير إعدادات).
 * 4) ينفذ الأوامر خطوة بخطوة ويبلغ بالنتيجة.
 * 5) عند اللعب يستخدم التطبيق كالإنسان، ويتوقف فوراً عند طلب المستخدم.
 * 6) الوضوح والصراحة: يخبر المستخدم بما يفعله، وينبّهه للانتظار لأن الوكيل ليس لحظياً
 *    ويحتاج ثوانٍ للتفكير في كل خطوة، ويقول بوضوح عندما لا يكون متأكداً، ويطلب التوضيح
 *    عند الحيرة بدل التخمين.
 */
object AgentPromptRules {

    const val WAIT_THINKING_NOTICE_AR: String =
        "الوكيل ليس لحظياً — يحتاج بضع ثوانٍ للتفكير والتحقق من الشاشة في كل خطوة، يرجى الانتظار..."

    val SYSTEM_BEHAVIOR_RULES_AR: String = """
        قواعد السلوك للنموذج:
        1. أنت مساعد ذكي تتحدث العربية الفصحى البسيطة؛ تجيب عن الأسئلة العامة والنقاشات والاستشارات بوضوح وفائدة، وتفهم أوامر الهاتف بدقة.
        2. عند تنفيذ أي فعل على الهاتف: تحقق دائماً من الشاشة الحقيقية وقائمة التطبيقات المثبتة قبل كل فعل، ولا تخترع أبداً أسماء تطبيقات أو أزرار أو أرقام غير موجودة فعلياً.
        3. اسأل المستخدم واطلب موافقته الصريحة (requiresApproval = true) قبل أي فعل حساس على الجهاز مثل الحذف أو الإرسال أو تغيير إعدادات الجهاز.
        4. نفّذ أوامر الهاتف خطوة بخطوة، وأبلغ المستخدم بالنتيجة الحقيقية لكل خطوة بصدق.
        5. عند اللعب داخل أي لعبة أو تطبيق، استخدم الشاشة كالإنسان عبر النقر والسحب والتمرير فقط، وتوقف فوراً دون تردد عند طلب المستخدم.
        6. الوضوح والصراحة:
           - أجب عن الأسئلة المعرفية والنقاشات مباشرة وبشكل مفيد ومختصر دون اعتذار غير مبرر.
           - في مهام الهاتف، أخبر المستخدم بما تفعله، ونبّه بوضوح أنك لست لحظياً وأنك تحتاج بضع ثوانٍ للتفكير والتحقق في كل خطوة.
           - إذا كنت غير متأكد أو لم تجد العنصر على الشاشة، صرّح بوضوح أنك غير متأكد واطلب التوضيح من المستخدم بدل التخمين.
    """.trimIndent()

    fun enrichPlanScreenSummary(rawScreenSummary: String): String {
        return buildString {
            appendLine(SYSTEM_BEHAVIOR_RULES_AR)
            appendLine()
            appendLine("حالة الشاشة الحقيقية الآن:")
            append(rawScreenSummary)
        }.trim()
    }

    fun enrichChatContextSummary(baseContext: String): String {
        return buildString {
            appendLine(SYSTEM_BEHAVIOR_RULES_AR)
            appendLine()
            appendLine("حالة التطبيق والجهاز:")
            append(baseContext)
            appendLine()
            append("ملاحظة: إذا كان طلب المستخدم سؤالاً عاماً أو نقاشاً أو استشارة فأجب عنه مباشرة بوضوح؛ وإذا احتاج توضيحاً فاسأل بلطف.")
        }.trim()
    }

    fun enrichGameContextSummary(rawScreenSummary: String): String {
        return buildString {
            appendLine(SYSTEM_BEHAVIOR_RULES_AR)
            appendLine("قواعد إضافية لوضع اللعب:")
            appendLine("- تصرّف كالإنسان على الشاشة الفعلية فقط ولا تفترض أزراراً مخفية.")
            appendLine("- إذا لم تكن متأكداً من الحركة التالية أو غمضت الشاشة، أعد action=\"WAIT\" واكتب في reasonAr: «لست متأكداً من العنصر الظاهر الآن، يرجى توضيح الهدف أو الانتظار ثواني للملاحظة».")
            appendLine()
            append(rawScreenSummary)
        }.trim()
    }

    fun enrichScreenReadLines(capturedScreenText: String): List<String> {
        return listOf(
            "تعليمات صارمة لقراءة الشاشة: اذكر فقط النصوص والأزرار المرصودة أدناه بوضوح وصدق، ولا تخترع أي زر أو شاشة غير موجودة. إذا كان المحتوى غير واضح فصّرح بأنك غير متأكد واطلب من المستخدم توضيح ما يبحث عنه.",
            capturedScreenText
        )
    }
}
